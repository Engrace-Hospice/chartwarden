/**
 * scripts/db/generate-permission-mirror-migration.ts - emit a migration that inserts the WHOLE permission catalog
 * into the `permission` mirror (ON CONFLICT DO NOTHING).
 *
 * WHY. `role_permission.permission_key` has a foreign key to `permission`, and outside the dev seeds nothing
 * populated the mirror except the handful of keys individual migrations inserted for their own grants (GAP-006).
 * Without the rows, a materialized tenant role cannot be granted the keys it should hold. The mirror is
 * read-only to the app role, so a migration is the only production writer.
 *
 * Usage: bun run scripts/db/generate-permission-mirror-migration.ts packages/db/migrations/0600_permission_mirror_full_catalog.sql
 * Re-run (to a NEW migration number) when the catalog gains keys; existing rows are never overwritten.
 */
import { writeFileSync } from "node:fs";
import { allPermissionMirrorRows } from "@wardenx/auth";

const target = process.argv[2];
if (!target) throw new Error("usage: generate-permission-mirror-migration.ts <output.sql>");

const q = (value: string): string => `'${value.replace(/'/g, "''")}'`;
const rows = [...allPermissionMirrorRows()].sort((a, b) => a.key.localeCompare(b.key));
const values = rows
  .map(
    (r) =>
      `  (${q(r.key)}, ${q(r.resource)}, ${q(r.action)}, ${q(r.category)}, ${q(r.defaultAbac)}, ${q(r.description)})`,
  )
  .join(",\n");

writeFileSync(
  target,
  `-- GAP-006 - mirror the whole permission catalog into \`permission\` so materialized tenant roles can be granted
-- their default keys (role_permission.permission_key has an FK to permission, and the mirror is read-only to the
-- app role; the dev-only \`db:sync:permissions\` was the only other writer). Generated by
-- scripts/db/generate-permission-mirror-migration.ts from allPermissionMirrorRows(); ${rows.length} keys.
-- Additive and idempotent: ON CONFLICT DO NOTHING never overwrites a row an earlier migration or a sync inserted.
INSERT INTO "permission" ("key", "resource", "action", "category", "default_abac", "description") VALUES
${values}
ON CONFLICT ("key") DO NOTHING;
`,
);
console.log(`wrote ${rows.length} permission mirror rows to ${target}`);
