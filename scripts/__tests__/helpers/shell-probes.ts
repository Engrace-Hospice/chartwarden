/** The discriminating probes of one shell as [args, markers]. */
export const exactProbes = (shell: string): Array<readonly [string[], string]> =>
  EXACT_PROBES.map((line) => line.split("|") as [string, string, string])
    .filter(([name]) => name === shell)
    .map(([, args, ran]) => [args === "" ? [] : args.split(" "), ran] as const);
