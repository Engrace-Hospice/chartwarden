// apps/web/src/modules/11-orders — the M11 read/WRITE access layer the §5 screens share
// (Track B / ADR-0030; #91).
//
// Until this file, `apps/web/src/modules/11-orders` issued ZERO mutations: 2731 lines across seven
// screens, every one of them a read. Four of those screens are QUEUES — Signature Inbox,
// Cosign-Pending, Verbal-Expiring, Results-Pending-Review — whose entire reason to exist is an action
// they did not offer. A physician could open a queue of orders awaiting their signature and have no way
// to sign one.
//
// Every wire shape below is a TYPE ALIAS into the generated `operations` map (regenerated by
// `bun run client:gen`), never a hand-copied interface — the same rule `13-emar/emar-api.ts` follows, and
// for the same reason: the argument and return types ARE the server contract, so a route or DTO drift is
// a compile error here rather than a runtime surprise in a screen.
//
// WHAT THE SERVER OWNS, WHICH NOTHING HERE SECOND-GUESSES.
//
//   • §2.2 lifecycle. The client asks for a transition; the SERVER decides whether the order is in a
//     state that permits it. No screen pre-computes "this is signable" as an authorization.
//   • §4.7 ABAC. `signer_eligible` reads the caller's discipline from their session role grants, never
//     from anything sent here. A 403 is the answer, surfaced verbatim, not a case to route around.
//   • §2.5 cosignature requirement, resolved at `request-signature` time. The client renders the posture
//     the read returns; it does not decide who must cosign.
//
// NO STEP-UP, DELIBERATELY. The `screens.ts` header this change replaces listed "the sign step-up" among
// the deferred write surfaces. There is none to defer: `POST /api/v1/orders/:id/sign` mounts
// `[SIGN, ABAC_SIGN]` and nothing else, `requireStepUp` appears nowhere in M11, and the module spec
// (v0_4) does not mention step-up at all. M8's encounter signature does require one, which is the likely
// source of the assumption. Building a re-authentication ceremony the server never asks for would be
// pure client-side theatre — ADR-0030 puts every enforcement point on the server — so this offers the
// signature the server actually accepts. If M11 SHOULD require step-up that is a spec decision and a
// server change, not a modal.
import type { ApiClient, operations } from "@wardenx/ui";

// ── schema-derived type extraction (same four helpers as emar-api.ts) ───────────────────────────────────

/** The `application/json` payload of an openapi-fetch response/request-body slot. */
type Json<T> = T extends { content: { "application/json": infer B } } ? B : never;
/** The success body of operation `Op` — 200 or 201, whichever the route actually sends. */
type Ok<Op> = Op extends { responses: { 200: infer R } }
  ? Json<R>
  : Op extends { responses: { 201: infer R } }
    ? Json<R>
    : never;
/** The request body of operation `Op`. */
type ReqBody<Op> = Op extends { requestBody?: infer RB } ? Json<RB> : never;

// ── wire shapes ────────────────────────────────────────────────────────────────────────────────────────

/** One order as every M11 write returns it — the row the caller re-renders after committing. */
export type OrderView = Ok<operations["postApiV1OrdersByIdSign"]>;
export type SignOrderBody = ReqBody<operations["postApiV1OrdersByIdSign"]>;
export type CosignOrderBody = ReqBody<operations["postApiV1OrdersByIdCosign"]>;
export type DiscontinueOrderBody = ReqBody<operations["postApiV1OrdersByIdDiscontinue"]>;
export type CompleteOrderBody = ReqBody<operations["postApiV1OrdersByIdComplete"]>;
export type RecordVerbalBody = ReqBody<operations["postApiV1OrdersByIdVerbal"]>;

/** The §2.5 cosigner roles the server accepts. Derived, so a vocabulary change is a compile error. */
export type CosignerRole = CosignOrderBody["cosignerRole"];
/** The §2.3 discontinuation reasons the server accepts. */
export type DiscontinueReason = DiscontinueOrderBody["reason"];

/**
 * The outcome of one write. A DISCRIMINATED result rather than a thrown error, because every caller here
 * has to render the failure in place — a queue row that silently stops responding is the failure mode
 * this whole change exists to end.
 */
export type WriteResult =
  | { readonly ok: true; readonly order: OrderView }
  | { readonly ok: false; readonly status: number | null; readonly message: string };

/**
 * Turn an openapi-fetch error into copy a clinician can act on.
 *
 * The status codes are NOT flattened into "something went wrong": each one means a different next step,
 * and 403 in particular must read as a refusal rather than a bug, since `signer_eligible` denying is the
 * control working. `409` is the §2.2 state machine — the order moved under the caller, which on a shared
 * queue is ordinary rather than exceptional.
 */
function failure(status: number | undefined, body: unknown): WriteResult {
  const code = typeof status === "number" ? status : null;
  const detail =
    body && typeof body === "object" && "message" in body && typeof body.message === "string"
      ? body.message
      : null;
  const message =
    code === 403
      ? (detail ?? "Your role is not eligible to take this action on this order.")
      : code === 409
        ? (detail ?? "This order changed before your action was applied. Reload the queue.")
        : code === 404
          ? "That order is no longer available to you."
          : code === 422
            ? (detail ?? "The server rejected the details supplied.")
            : (detail ?? "The action could not be completed.");
  return { ok: false, status: code, message };
}

/** ISO instant for a `date-time` field the server records as client-observed time. */
export const nowIso = (): string => new Date().toISOString();

// ── the five §2.2 write ceremonies the §5 queues and the detail pane are built around ──────────────────

/** §2.2 — sign a pending order (→ active). `signer_eligible` ABAC floor is the server's (§4.7). */
export async function signOrder(
  client: ApiClient,
  id: string,
  body: SignOrderBody,
): Promise<WriteResult> {
  const { data, error, response } = await client.POST("/api/v1/orders/{id}/sign", {
    params: { path: { id } },
    body,
  });
  if (error || !data) return failure(response?.status, error);
  return { ok: true, order: data as OrderView };
}

