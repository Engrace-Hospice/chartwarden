// apps/web/src/modules/14-idg — the M14 read/WRITE access layer the §5 IDG screens share
// (Track B / ADR-0030; #91).
//
// Until this file, `apps/web/src/modules/14-idg` issued ZERO mutations: 2071 lines across seven
// screens, every one of them a read. The interdisciplinary group meeting is where 42 CFR 418.56(b)
// says the plan of care is established and §418.56(d) says it is reviewed at least every 15 calendar
// days — and the Live Meeting Surface was a list of patient ids. Nobody could check in, put an item
// on the agenda, record what the group decided, assign a follow-up, or adjourn. The module's own
// review-clock sweep escalates a patient at T-3 / T-0 / T+1 against a floor that only ADJOURNMENT
// resets, so the one control that stops the escalation had no caller.
//
// Every wire shape below is a TYPE ALIAS into the generated `operations` map (regenerated by
// `bun run client:gen`), never a hand-copied interface — the same rule `13-emar/emar-api.ts` and
// `07-care-plan/care-plan-api.ts` follow, so a route or DTO drift is a compile error here rather than
// a runtime surprise in a screen.
//
// WHAT THE SERVER OWNS, WHICH NOTHING HERE RE-DECIDES (ADR-0030 — no frontend authz).
//
//   • §2.2 the meeting state machine. The client asks for a transition; `transitionMeeting` decides
//     whether the meeting is in a state that permits it. No screen pre-computes "this is adjournable".
//   • §2.7 QUORUM. `quorate_decision` reads the attendance roster server-side and refuses a
//     non-quorate decision with a 422. The roster this file now reads back is rendered as INFORMATION —
//     "the group looks quorate" — never as a reason to disable the Record button. A client that
//     decided quorum would be a second, divergent implementation of the CoP composition rule.
//   • §2.2 D13 the adjournment step-up. `POST .../adjourn` resolves the caller's REAL session through
//     M2's `SessionContextResolver` and raises `STEP_UP_REQUIRED` (412) itself (F-028 removed the
//     `x-step-up` header this route used to trust). This file cannot make a session fresh; it sends
//     the request and renders the 412 as the re-authentication prompt it is.
//   • GAP-020/091 the per-patient 15-day review floor on cancel/reschedule, and whether the caller may
//     override it (`per_patient_review_floor_clear` + `idg.override_review_floor` + a fresh step-up).
//
// TWO CONTROLS ARE DELIBERATELY ABSENT, because the routes behind them do not do what their names say:
//
//   • REMOVE AN AGENDA ITEM. `DELETE /api/v1/idg/agenda/:id` is a tenant-checked NO-OP — the service
//     comment says so ("no DELETE grant + no tombstone column on the append-only agenda … → tenant-
//     checked no-op"). It returns `{ removed: true }` and removes nothing. A Remove button over that
//     route would report success for work the server does not do, which is the F-007 rule #91's own
//     acceptance criteria set. Removing attendance IS offered: that one soft-excuses the row
//     (`status: "excused"`, out of the quorum present-set), which is a real, documented effect.
//   • THE care_plan_update DECISION beyond `problem_add`. Five of its six mutation ops address M7 plan
//     elements by uuid (`problemId` / `goalId` / `interventionId`), which needs the plan-element picker
//     that belongs with the M07 care-plan surface. `problem_add` carries no id and is offered.
