-- M30 HQRP & Quality §3.6 — write-audit triggers (consumes the M4 generateAuditTrigger generator).
--
-- Every M30 table carries organization_id NOT NULL, so every table gets BOTH an RLS policy (0067) and a
-- write-audit trigger (the arch:gaps phi-guards floor). Each audit_phi_write_<table>() is the canonical M4
-- shape: SECURITY DEFINER, SET search_path = pg_catalog, public, OWNER TO wardenx_audit_writer, org context
-- keyed on COALESCE(NEW.organization_id, OLD.organization_id), retention_class 'compliance'. The §3.6 PHI /
-- SUD-sensitive / ciphertext / free-text columns are scrubbed via the audit_scrub(to_jsonb(...), ARRAY[...])
-- 2nd-arg denylist (the EVV coords_cipher / M34 key-material precedent):
--   • quality_measure_value.computation_snapshot (large opaque seam state → hash is the change-marker)
--   • cahps_vendor_binding.configuration_cipher + cahps_decedent_sample.primary_caregiver_contact_cipher (ciphertext)
--   • qapi_pip.{root_cause_analysis_text,intervention_plan_text,conclusion_text} + qapi_governance_minutes.minutes_text (may name staff/patients)
--   • sra_finding.{vulnerability_description,impact_description} + sra_remediation.description_text (security-posture sensitive)
--   • incident_report.kind_data (narrative/witness/quotes free-text PHI) + infection_surveillance_event.{exposure_source,outcome}
--   • mortality_review.{clinical,satisfaction,compliance}_dimension_data (free-text dimension members)
-- Tables carrying a patient identifier add it to the audit context jsonb (incident_report.patient_id,
-- infection_surveillance_event.patient_id, mortality_review.deceased_patient_id, cahps_decedent_sample.deceased_patient_id).
-- NB: the 4 partitioned tables get the trigger on the PARTITIONED PARENT only — FOR EACH ROW propagates to
-- every partition (PG11+), OLD/NEW bound to the routed partition row.
CREATE OR REPLACE FUNCTION audit_phi_write_quality_measure_value() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_before jsonb;
  v_after jsonb;
  v_cols text[] := ARRAY['computation_snapshot']::text[];
BEGIN
  v_before := CASE WHEN TG_OP IN ('UPDATE','DELETE')
    THEN audit_scrub(to_jsonb(OLD), v_cols) ELSE NULL END;
  v_after := CASE WHEN TG_OP IN ('INSERT','UPDATE')
    THEN audit_scrub(to_jsonb(NEW), v_cols) ELSE NULL END;
  INSERT INTO audit_event (
    organization_id, actor_user_id, actor_kind, event_type, resource_kind,
    resource_id, correlation_id, outcome, severity, before, after,
    context, retention_class
  ) VALUES (
    COALESCE(NEW.organization_id, OLD.organization_id),
    NULLIF(current_setting('app.user_id', true), '')::uuid,
    'system',
    'quality_measure_value.' || lower(TG_OP),
    'quality_measure_value',
    COALESCE(NEW.id, OLD.id),
    COALESCE(NULLIF(current_setting('app.correlation_id', true), ''), 'system'),
    'success', 'info', v_before, v_after,
    jsonb_build_object(
      'provider_entity_id', NULLIF(current_setting('app.provider_entity_id', true), ''),
      'location_id', NULLIF(current_setting('app.location_id', true), '')),
    'compliance'
  );
  RETURN COALESCE(NEW, OLD);
END $$;--> statement-breakpoint
