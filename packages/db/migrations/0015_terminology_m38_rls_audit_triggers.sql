-- 5. value_set_tenant_extension — canonical M4 generated write-audit trigger (§3.8) ------------
-- Generated by @wardenx/audit generateAuditTrigger({ table:'value_set_tenant_extension',
-- resourceKind:'term_value_set_extension', denylist:[], retentionClass:'compliance' }).
CREATE OR REPLACE FUNCTION audit_phi_write_value_set_tenant_extension() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_before jsonb;
  v_after jsonb;
BEGIN
  v_before := CASE WHEN TG_OP IN ('UPDATE','DELETE')
    THEN audit_scrub(to_jsonb(OLD), ARRAY[]::text[]) ELSE NULL END;
  v_after := CASE WHEN TG_OP IN ('INSERT','UPDATE')
    THEN audit_scrub(to_jsonb(NEW), ARRAY[]::text[]) ELSE NULL END;
  INSERT INTO audit_event (
    organization_id, actor_user_id, actor_kind, event_type, resource_kind,
    resource_id, correlation_id, outcome, severity, before, after,
    context, retention_class
  ) VALUES (
    COALESCE(NEW.organization_id, OLD.organization_id),
    NULLIF(current_setting('app.user_id', true), '')::uuid,
    'user',
    'term_value_set_extension.' || lower(TG_OP),
    'term_value_set_extension',
    COALESCE(NEW.id, OLD.id),
    COALESCE(NULLIF(current_setting('app.correlation_id', true), ''), 'system'),
    'success', 'info', v_before, v_after,
    jsonb_build_object(
      'provider_entity_id', NULLIF(current_setting('app.provider_entity_id', true), ''),
      'location_id', NULLIF(current_setting('app.location_id', true), '')),
    'compliance'
  );
  RETURN COALESCE(NEW, OLD);
END $$;--> statement-breakpoint
ALTER FUNCTION audit_phi_write_value_set_tenant_extension() OWNER TO wardenx_audit_writer;--> statement-breakpoint
CREATE TRIGGER "trg_audit_value_set_tenant_extension" AFTER INSERT OR UPDATE OR DELETE ON value_set_tenant_extension
  FOR EACH ROW EXECUTE FUNCTION audit_phi_write_value_set_tenant_extension();--> statement-breakpoint

-- 5b. Harden the M1 baseline audit trigger for non-UUID primary keys (§3.8) -------------------
-- The §3.8 plan reuses M1's `wardenx_audit_trigger()` (0004) for the 12 platform tables, citing the
-- `permission` precedent (0009). But `permission`'s PK is `key` — it has NO `id` column, so the
-- function's `v_rid := (… ->> 'id')::uuid` reads NULL and skips the cast. `code_system` (PK = the
-- `code_system_id` enum, e.g. 'icd10cm') and `value_set` (PK = a text slug) DO carry an `id`, so the
-- original unconditional `::uuid` cast raises 22P02 on every canonical write — the module could not
-- load. We re-assert the canonical baseline body here with one change: `v_rid` casts only when the id
-- is UUID-shaped, else stays NULL (resource_id is nullable). UUID-PK tables are unaffected; the
-- non-UUID platform tables now audit with a NULL resource_id (version-grained history additionally
-- lives in terminology_update_log). Surfaced by the live-PG suite (rls-isolation.live.test.ts §9.2).
CREATE OR REPLACE FUNCTION wardenx_audit_trigger()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_before jsonb;
  v_after jsonb;
  v_org uuid;
  v_rid uuid;
  v_id text;
BEGIN
  IF TG_TABLE_NAME LIKE 'audit_event%'
     OR TG_TABLE_NAME = ANY (ARRAY['idempotency_key', 'outbox_event']) THEN
    RETURN COALESCE(NEW, OLD);
  END IF;

  IF TG_OP = 'DELETE' THEN
    v_before := to_jsonb(OLD); v_after := NULL;
  ELSIF TG_OP = 'UPDATE' THEN
    v_before := to_jsonb(OLD); v_after := to_jsonb(NEW);
  ELSE
    v_before := NULL; v_after := to_jsonb(NEW);
  END IF;

  IF TG_TABLE_NAME = 'organization' THEN
    v_org := COALESCE(v_after->>'id', v_before->>'id')::uuid;
  ELSE
    v_org := NULLIF(COALESCE(v_after->>'organization_id', v_before->>'organization_id'), '')::uuid;
  END IF;
  IF v_org IS NULL THEN
    v_org := NULLIF(current_setting('app.org_id', true), '')::uuid;
  END IF;

  -- Only cast a UUID-shaped id; non-UUID platform PKs (code_system enum, value_set slug) → NULL.
  v_id := NULLIF(COALESCE(v_after->>'id', v_before->>'id'), '');
  IF v_id ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' THEN
    v_rid := v_id::uuid;
  ELSE
    v_rid := NULL;
  END IF;

  INSERT INTO audit_event (
    organization_id, actor_kind, event_type, resource_kind, resource_id,
    correlation_id, outcome, severity, before, after, retention_class
  ) VALUES (
    v_org, 'system', TG_TABLE_NAME || '.' || lower(TG_OP), TG_TABLE_NAME, v_rid,
    'db-trigger', 'success', 'info', v_before, v_after, 'compliance'
  );

  RETURN COALESCE(NEW, OLD);
END;
$$;--> statement-breakpoint

