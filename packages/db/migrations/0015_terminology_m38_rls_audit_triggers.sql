--
-- Tables + the pg_trgm/vector extensions land in 0014 (drizzle-generated, hand-augmented with
-- the two CREATE EXTENSIONs). This migration locks the platform-shared RLS pattern, the
-- `terminology_loader` least-privilege writer role, and the per-table write-audit triggers.
--
-- M38 owns 13 tables (the manifest is authoritative; the spec's §3.7/§3.8 example lists the
-- full 19-system superset, but only ICD-10-CM/SNOMED/LOINC/RxNorm ship in Phase 1 — §1.2, the
-- `wave-b-m38-t01` scope note). Twelve are platform-shared canonical reference (NON_ORG_SCOPED):
--   code_system, code_system_version, the four Phase-1 per-system concept tables, value_set,
--   value_set_member, value_set_expansion, deprecation_mapping, concept_embedding,
--   terminology_update_log.
-- The thirteenth, value_set_tenant_extension, is the ONLY org-scoped table (§3.5/§3.7).
--
-- AUDIT TRIGGER STRATEGY (§3.8 intent, reconciled with the M4 generator's contract):
--   • value_set_tenant_extension is org-scoped and tenant-writable, so it gets the canonical M4
--     `generateAuditTrigger()` output (audit_phi_write_*, wardenx_audit_writer SECURITY DEFINER,
--     audit_scrub with an empty denylist — terminology data is non-PHI, full diffs are the point).
--   • The 12 platform tables carry NO organization_id by design, so the M4 generator (which keys
--     `COALESCE(NEW.organization_id, OLD.organization_id)`) cannot run on them. They instead get
--     M1's null-safe baseline `wardenx_audit_trigger()` (0004) — the SAME treatment platform
--     reference tables already receive (`permission`, 0009): a full unscrubbed before/after diff
--     attributed to the platform context (app.org_id NULL on a loader-context write). This honors
--     §3.8 ("every terminology table is audited; full diffs are the point") with the buildable
--     mechanism. Version-granularity change history additionally lives in terminology_update_log.

-- 1. Least-privilege writer role (§3.7) --------------------------------------------------------
-- Owns terminology canonical INSERT/UPDATE; granted to the SECURITY DEFINER load functions in
-- packages/terminology only. wardenx_app NEVER writes canonical terminology (§7.4).
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'terminology_loader') THEN
    CREATE ROLE terminology_loader NOLOGIN;
  END IF;
END $$;--> statement-breakpoint
COMMENT ON ROLE terminology_loader IS
  'Owns terminology canonical INSERT/UPDATE. Granted to SECURITY DEFINER load functions in packages/terminology only. wardenx_app NEVER writes terminology (M38 §3.7/§7.4).';--> statement-breakpoint

-- 2. Platform-shared canonical tables — read-all RLS + loader-only writes (§3.7) ---------------
-- wardenx_app may only SELECT (USING (true) — non-tenant reference data, visible to every org);
-- INSERT/UPDATE is granted to terminology_loader; wardenx_admin keeps ALL (migration/ops).
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'code_system','code_system_version',
    'concept_icd10cm','concept_snomed','concept_loinc','concept_rxnorm',
    'value_set','value_set_member','value_set_expansion',
    'deprecation_mapping','concept_embedding','terminology_update_log'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('CREATE POLICY %I_read ON %I FOR SELECT TO wardenx_app USING (true)', t, t);
    EXECUTE format('GRANT SELECT ON %I TO wardenx_app', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE ON %I TO terminology_loader', t);
    EXECUTE format('GRANT ALL ON %I TO wardenx_admin', t);
  END LOOP;
END $$;--> statement-breakpoint

