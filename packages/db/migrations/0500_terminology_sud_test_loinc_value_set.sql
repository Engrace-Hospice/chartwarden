-- GAP-086 — seed the M38 platform value set `sud_test_loinc` (42 CFR Part 2 substance-use-disorder lab tests).
--
-- WHAT WAS WRONG. M29's inbound lab path (inbound-seam-ports.ts `classifyLoinc`) redacts a result as SUD
-- only when its LOINC code is a member of the M38 value set `sud_test_loinc` (plus the tenant's own
-- `value_set_tenant_extension` rows). That value set was never seeded: the `value_set` row did not exist, so
-- `isMemberOf` was false for EVERY code and no SUD result was ever redacted at ingest (a compliance gap).
--
-- WHAT THIS DOES. DML only (no DDL). Inserts the platform-shared `value_set` definition (scope 'platform',
-- no organization — same non-tenant reference-data class as every M38 canonical table) and its
-- `value_set_member` rows (system 'loinc'). Idempotent: `ON CONFLICT DO NOTHING` on the value_set PK and on
-- `value_set_member_unique` (value_set_id, system_id, code, member_effective). Tenants ADD to the set through
-- `value_set_tenant_extension` (add-only, org-scoped RLS); they never write the platform rows. Writes go
-- through the migration owner, the same door the other platform seed migrations use (0080); the M38
-- write-audit triggers still fire and record each row.
--
-- The member list is generated data: packages/terminology/src/seed/sud-test-loinc.ts is the source of truth
-- and a unit test (packages/terminology/__tests__/sud-test-loinc.test.ts) asserts this file and that list agree
-- code-for-code and name-for-name. Each name is the LOINC long common name verbatim (NLM Clinical Table Search
-- Service, fetched 2026-10-07). Inclusion rule, exclusions and the REQUIRED clinical/compliance review: see
-- the header of that file and docs/history/m29-m38-sud-test-loinc-seed.md.
--
-- member_effective = 1970-01-01 so an old-dated observation is still classified (conservative: redact on doubt).
-- `annotations` carries the LOINC long common name (`display`) and whether LOINC marks the code deprecated.

