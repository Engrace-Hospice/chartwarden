-- M4 Audit §3.3 / Wave-A interplay note 2 (M4-T10) — write-audit trigger BACK-FILL.
--
-- M1–M4 each shipped a BASELINE capture trigger (M1's wardenx_audit_trigger(), 0004/0006/0009/
-- 0012) so the phi-guards fitness gate stayed green while the canonical generator was still being
-- built. M4 owns that generator (M4-T02, generateAuditTrigger() — column-level denylist scrubbing,
-- wardenx_audit_writer SECURITY DEFINER ownership, the INSERT-only audit_event policy, M04-F06).
-- This migration NORMALIZES every genuinely org-scoped M1–M4 table (organization_id + id) from the
-- baseline to the canonical generated trigger (Wave-A acceptance #3).
--
-- NOT back-filled (keep the baseline / no trigger by design):
--   • organization, location — scoped without an organization_id column (own id / join via parent);
--   • idempotency_key, outbox_event — high-churn transactional-mechanism tables the baseline no-ops;
--   • permission, state_retention_override, audit_denylist_catalog, audit_action_catalog — platform
--     reference (NON_ORG_SCOPED); two_factor, passkey — user-scoped, not org-scoped;
--   • audit_event + its monthly partitions — append-only & self-auditing (the generator refuses it).
--
-- Idempotent: each baseline trigger is DROPped IF EXISTS before the generated one is attached, and
-- the wardenx_audit_writer INSERT grant + audit_event policy (auditWriterGrantsDDL) — required
-- because the generated functions run as wardenx_audit_writer, not the table owner — is (re)applied
-- first (DROP POLICY IF EXISTS). audit_scrub() is already present from 0012 (M4-T05).

-- 1. Ensure the wardenx_audit_writer append path exists (M04-F06 #2) -----------
GRANT INSERT ON audit_event TO wardenx_audit_writer;--> statement-breakpoint
DROP POLICY IF EXISTS audit_writer_insert ON audit_event;--> statement-breakpoint
CREATE POLICY audit_writer_insert ON audit_event
  FOR INSERT TO wardenx_audit_writer WITH CHECK (true);--> statement-breakpoint

-- 2. Per-table back-fill --------------------------------------------------------
-- provider_entity: baseline → canonical generated trigger
DROP TRIGGER IF EXISTS "provider_entity_audit" ON provider_entity;--> statement-breakpoint
CREATE OR REPLACE FUNCTION audit_phi_write_provider_entity() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_before jsonb;
  v_after jsonb;
BEGIN
  v_before := CASE WHEN TG_OP IN ('UPDATE','DELETE')
    THEN audit_scrub(to_jsonb(OLD), ARRAY[]::text[]) ELSE NULL END;
  v_after := CASE WHEN TG_OP IN ('INSERT','UPDATE')
    THEN audit_scrub(to_jsonb(NEW), ARRAY[]::text[]) ELSE NULL END;
  INSERT INTO audit_event (
    organization_id, actor_user_id, actor_kind, event_type, resource_kind,
    resource_id, correlation_id, outcome, severity, before, after,
    context, retention_class
  ) VALUES (
    COALESCE(NEW.organization_id, OLD.organization_id),
    NULLIF(current_setting('app.user_id', true), '')::uuid,
    'user',
    'provider_entity.' || lower(TG_OP),
    'provider_entity',
    COALESCE(NEW.id, OLD.id),
    COALESCE(NULLIF(current_setting('app.correlation_id', true), ''), 'system'),
    'success', 'info', v_before, v_after,
    jsonb_build_object(
      'provider_entity_id', NULLIF(current_setting('app.provider_entity_id', true), ''),
      'location_id', NULLIF(current_setting('app.location_id', true), '')),
    'compliance'
  );
  RETURN COALESCE(NEW, OLD);
END $$;--> statement-breakpoint
ALTER FUNCTION audit_phi_write_provider_entity() OWNER TO wardenx_audit_writer;--> statement-breakpoint
CREATE TRIGGER "trg_audit_provider_entity" AFTER INSERT OR UPDATE OR DELETE ON provider_entity
  FOR EACH ROW EXECUTE FUNCTION audit_phi_write_provider_entity();--> statement-breakpoint
